/**
 * 2BHK menus — view-only showcase data (no ordering).
 * Transcribed from the printed "Food Menu Card" and "Bar Dining Menu".
 * Prices are strings so multi-variant values ("400 / 450 / 500") survive as-is;
 * the UI prefixes ₹ and comma-groups each number. `veg`: true=veg, false=non-veg,
 * undefined=not applicable (drinks / mixed veg+non-veg combos).
 */

export interface MenuItem {
  name: string;
  desc?: string;
  price: string;
  /** clarifies multi-price columns, e.g. "Chicken / Bacon / Prawn" */
  priceNote?: string;
  /** drinks only — spirit base, e.g. "White Rum Base" */
  base?: string;
  veg?: boolean;
}

export interface MenuSection {
  title: string;
  /** small caption under the title, e.g. cuisine zone or price columns */
  subtitle?: string;
  note?: string;
  items: MenuItem[];
}

export interface Menu {
  key: string;
  label: string;
  intro?: string;
  sections: MenuSection[];
}

